"""Generate a draft incident report from an NGINX access log using a local LLM.

The log is first summarised by preprocess.py (counts, masked IPs), then the
summary is sent to the LLM, and the analysis is written to report.md.
Usage: python3 incident_assistant.py <logfile>
"""
import sys
from openai import OpenAI, APIConnectionError
from preprocess import summarize

MODEL = "llama3.1:8b"
# Rules for the LLM: stick to the summary, admit uncertainty, fixed report structure
SYSTEM_PROMPT = """You are a Site Reliability Engineer analysing an incident.
Use ONLY the log summary provided. Do not invent facts.
If the information is not enough to conclude, say so explicitly.
Answer in Markdown with these sections:
## Summary
## Timeline
## Probable causes (with a confidence level: low, medium or high)
## Diagnostic commands to run (read-only commands only)
## Recommended next steps"""

if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Usage: python3 incident_assistant.py <logfile>", file=sys.stderr)
        sys.exit(2)
    try:
        summary = summarize(sys.argv[1])
    except FileNotFoundError:
        print(f"File not found: {sys.argv[1]}", file=sys.stderr)
        sys.exit(1)
    try:
        # Ollama exposes an OpenAI-compatible API: switching to a hosted endpoint
        # (e.g. OVHcloud AI Endpoints) only means changing base_url and api_key
        client = OpenAI(base_url="http://localhost:11434/v1", api_key="ollama")
        # temperature=0 and a fixed seed reduce variation between runs,
        # but do not fully guarantee identical reports (see README)
        response = client.chat.completions.create(model=MODEL, temperature=0, seed=42, messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"Summary of NGINX access logs:\n\n{summary}"}
        ])
    except APIConnectionError:
        print("Cannot reach Ollama. Is it running? (sudo systemctl start ollama)", file=sys.stderr)
        sys.exit(1)
    analysis = response.choices[0].message.content
    # The report is a draft: an engineer must review it before acting on it
    with open("report.md", "w") as f:
        f.write(f"> Draft generated by a local LLM ({MODEL}). To be reviewed by an engineer.\n\n")
        f.write("## Log summary\n")
        f.write("```\n")
        f.write(f"{summary}\n")
        f.write("```\n\n")
        f.write(analysis + "\n")
    print("Report written to report.md")